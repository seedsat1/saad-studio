/** Simple Internationalization (i18n) Helper for Saad Studio */

export type Language = "en" | "ar";

let currentLang: Language = (localStorage.getItem("saad_lang") as Language) || "en";

export function getLanguage(): Language {
  return currentLang;
}

export function setLanguage(lang: Language) {
  currentLang = lang;
  localStorage.setItem("saad_lang", lang);
  window.dispatchEvent(new CustomEvent("saad-language-changed", { detail: lang }));
}

